import { afterEach, describe, expect, it } from "vitest";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createDb } from "../db/client.js";
import { SqliteKnowledgeStore } from "./sqlite-store.js";
import { WikiService } from "./wiki-service.js";
import { BuildQueue } from "./build-queue.js";
import type { LlmConfig } from "../config.js";
const cleanups: (() => void)[] = [];
afterEach(() => cleanups.splice(0).forEach((cleanup) => cleanup()));
describe("Wiki background model snapshot", () => {
  it("freezes the requested model and capability before a queued job begins", async () => {
    const dir = mkdtempSync(join(tmpdir(), "wiki-origin-"));
    const { db, raw } = createDb({ path: ":memory:" });
    cleanups.push(() => { raw.close(); rmSync(dir, { recursive: true, force: true }); });
    const store = new SqliteKnowledgeStore(db);
    const a = store.createWiki({ service_id: "service", team_id: "team", name: "a" }).row;
    const b = store.createWiki({ service_id: "service", team_id: "team", name: "b" }).row;
    const queue = new BuildQueue();
    let release!: () => void;
    const gate = new Promise<void>((resolve) => { release = resolve; });
    queue.enqueue(a.wiki_id, () => gate);
    queue.enqueue(b.wiki_id, () => gate);
    const configs: LlmConfig[] = [];
    let current: LlmConfig = { mode: "custom", protocol: "openai", provider: "custom", model: "model-a", apiKey: "synthetic-capability-a", baseUrl: "http://localhost/api/runtime/tencent/v1", maxTokens: 100, timeoutMs: 1000 };
    const service = new WikiService({ store, dataRoot: dir, queue, resolveJobLlm: () => current, worker: async (ctx) => { configs.push(ctx.llmConfig!); return { pageCount: 1 }; } });
    const result = service.ingest("service", "team", a.wiki_id);
    expect(result.kind === "ok" && result.generation_model).toBe("model-a");
    expect(JSON.stringify(result)).not.toContain("synthetic-capability-a");
    current.model = "mutated-after-enqueue";
    current = { ...current, model: "model-b", apiKey: "synthetic-capability-b" };
    service.ingest("service", "team", b.wiki_id);
    release();
    await queue.onIdle();
    expect(configs.map((c) => [c.model, c.apiKey])).toEqual([["model-a", "synthetic-capability-a"], ["model-b", "synthetic-capability-b"]]);
    expect(configs.every(Object.isFrozen)).toBe(true);
    expect(store.getWikiById("service", a.wiki_id)?.status).toBe("ready");
  });
});
